// Simple fuzzy: every character of query appears in order in target
function fuzzyMatch(query: string, target: string): boolean {
  let qi = 0;
  for (let i = 0; i < target.length && qi < query.length; i++) {
    if (target[i] === query[qi]) qi++;
  }
  return qi === query.length;
}

export function searchDestinations(query: string): string[] {
  const q = query.toLowerCase().trim();
  if (q.length < 2) return [];

  // Alias exact match
  const aliasMatch = ALIASES[q];
  const aliasResults: string[] = aliasMatch ? [aliasMatch] : [];

  // Partial alias matches (e.g. "beng" → bengaluru key)
  const partialAliasMatches = Object.entries(ALIASES)
    .filter(([key]) => key.startsWith(q) && ALIASES[key] !== aliasMatch)
    .map(([, val]) => val);

  // Tier 1: city name starts with query (highest priority)
  const startsWithMatches = DESTINATIONS.filter(d =>
    d.toLowerCase().startsWith(q) ||
    d.toLowerCase().split(',')[0].trim().startsWith(q)
  );

  // Tier 2: substring anywhere in destination
  const substringMatches = DESTINATIONS.filter(d =>
    d.toLowerCase().includes(q) && !startsWithMatches.includes(d)
  );

  // Tier 3: fuzzy matches (catches typos like "bangalor", "paries")
  const fuzzyMatches = q.length >= 4
    ? DESTINATIONS.filter(d => {
        const city = d.toLowerCase().split(',')[0].trim();
        return fuzzyMatch(q, city) && !startsWithMatches.includes(d) && !substringMatches.includes(d);
      })
    : [];

  const seen = new Set<string>();
  const results: string[] = [];
  for (const dest of [...aliasResults, ...partialAliasMatches, ...startsWithMatches, ...substringMatches, ...fuzzyMatches]) {
    if (!seen.has(dest)) {
      seen.add(dest);
      results.push(dest);
    }
  }

  return results.slice(0, 8);
}
